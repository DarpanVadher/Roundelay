ThemeData roundelayTheme(Brightness brightness) {
  final scheme = brightness == Brightness.dark ? roundelayDark : roundelayLight;
  return ThemeData(
    useMaterial3: true,
    colorScheme: scheme,
    scaffoldBackgroundColor: scheme.surface,
  );
}
